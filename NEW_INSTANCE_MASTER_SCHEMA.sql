-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- =====================================================
-- CORE PROJECT TABLES
-- =====================================================

CREATE TABLE IF NOT EXISTS projects (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name TEXT NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    is_active BOOLEAN DEFAULT true
);

CREATE TABLE IF NOT EXISTS project_users (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id UUID NOT NULL,
    role TEXT NOT NULL DEFAULT 'member',
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(project_id, user_id)
);

-- =====================================================
-- REFERENCE DATA TABLES
-- =====================================================

CREATE TABLE IF NOT EXISTS functional_areas (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    active BOOLEAN DEFAULT true,
    display_order INTEGER DEFAULT 999,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    project_id UUID REFERENCES projects(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS training_locations (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    active BOOLEAN DEFAULT true,
    display_order INTEGER DEFAULT 999,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    project_id UUID REFERENCES projects(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS project_roles (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    role_name VARCHAR(100) NOT NULL,
    description TEXT,
    active BOOLEAN DEFAULT true,
    display_order INTEGER DEFAULT 999,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    project_id UUID REFERENCES projects(id) ON DELETE CASCADE
);

-- =====================================================
-- COURSES TABLE
-- =====================================================

CREATE TABLE IF NOT EXISTS courses (
    course_id TEXT PRIMARY KEY,
    functional_area TEXT NOT NULL,
    duration_hrs NUMERIC NOT NULL,
    course_name TEXT,
    application TEXT,
    priority INTEGER NOT NULL DEFAULT 1,
    project_id UUID REFERENCES projects(id) ON DELETE CASCADE
);

-- =====================================================
-- END USERS TABLE
-- =====================================================

CREATE TABLE IF NOT EXISTS end_users (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    job_title TEXT,
    country TEXT,
    division TEXT,
    sub_division TEXT,
    training_location TEXT,
    project_role TEXT,
    project_id UUID REFERENCES projects(id) ON DELETE CASCADE,
    location_name TEXT
);

-- =====================================================
-- USER COURSE MAPPINGS TABLE (Individual Assignments)
-- =====================================================

CREATE TABLE IF NOT EXISTS user_course_mappings (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    end_user_id INTEGER NOT NULL REFERENCES end_users(id) ON DELETE CASCADE,
    course_id TEXT NOT NULL REFERENCES courses(course_id) ON DELETE CASCADE,
    assigned_by TEXT NOT NULL DEFAULT 'admin',
    assigned_date TIMESTAMPTZ DEFAULT NOW(),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_user_course UNIQUE(end_user_id, course_id)
);

-- =====================================================
-- TRAINING SCHEDULES & SESSIONS
-- =====================================================

CREATE TABLE IF NOT EXISTS training_schedules (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    version TEXT DEFAULT to_char(now(), 'YYYYMMDDHH24MISS'),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    created_by UUID,
    signed_off BOOLEAN DEFAULT false,
    criteria JSONB,
    project_id UUID REFERENCES projects(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS training_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    schedule_id UUID REFERENCES training_schedules(id) ON DELETE CASCADE,
    course_id TEXT NOT NULL,
    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    duration_hrs NUMERIC NOT NULL,
    training_location TEXT,
    max_attendees INTEGER,
    assigned_attendees INTEGER DEFAULT 0,
    project_id UUID REFERENCES projects(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS user_assignments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID NOT NULL REFERENCES training_sessions(id) ON DELETE CASCADE,
    end_user_id INTEGER NOT NULL REFERENCES end_users(id) ON DELETE CASCADE,
    course_id TEXT NOT NULL,
    assignment_status TEXT DEFAULT 'assigned',
    project_id UUID REFERENCES projects(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_user_session UNIQUE(session_id, end_user_id)
);

