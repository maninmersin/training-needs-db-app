-- Get all courses assigned to a user
CREATE OR REPLACE FUNCTION get_user_courses(p_end_user_id INTEGER)
RETURNS TABLE (
    course_id TEXT,
    course_name TEXT,
    functional_area TEXT,
    duration_hrs NUMERIC,
    assigned_by TEXT,
    assigned_date TIMESTAMPTZ
) AS $$
BEGIN
    RETURN QUERY
    SELECT
        c.course_id,
        c.course_name,
        c.functional_area,
        c.duration_hrs,
        ucm.assigned_by,
        ucm.assigned_date
    FROM user_course_mappings ucm
    JOIN courses c ON ucm.course_id = c.course_id
    WHERE ucm.end_user_id = p_end_user_id
    ORDER BY c.course_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Get all users assigned to a course
CREATE OR REPLACE FUNCTION get_course_users(p_course_id TEXT, p_project_id UUID)
RETURNS TABLE (
    end_user_id INTEGER,
    name TEXT,
    email TEXT,
    project_role TEXT,
    training_location TEXT,
    assigned_by TEXT,
    assigned_date TIMESTAMPTZ
) AS $$
BEGIN
    RETURN QUERY
    SELECT
        eu.id,
        eu.name,
        eu.email,
        eu.project_role,
        eu.training_location,
        ucm.assigned_by,
        ucm.assigned_date
    FROM user_course_mappings ucm
    JOIN end_users eu ON ucm.end_user_id = eu.id
    WHERE ucm.course_id = p_course_id
        AND ucm.project_id = p_project_id
    ORDER BY eu.name;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Bulk assign courses to users
CREATE OR REPLACE FUNCTION bulk_assign_courses(
    p_project_id UUID,
    p_user_ids INTEGER[],
    p_course_ids TEXT[],
    p_assigned_by TEXT DEFAULT 'bulk',
    p_replace_mode BOOLEAN DEFAULT false
)
RETURNS INTEGER AS $$
DECLARE
    v_user_id INTEGER;
    v_course_id TEXT;
    v_count INTEGER := 0;
BEGIN
    -- If replace mode, delete existing assignments for these users
    IF p_replace_mode THEN
        DELETE FROM user_course_mappings
        WHERE end_user_id = ANY(p_user_ids)
            AND project_id = p_project_id;
    END IF;

    -- Insert new assignments
    FOREACH v_user_id IN ARRAY p_user_ids
    LOOP
        FOREACH v_course_id IN ARRAY p_course_ids
        LOOP
            INSERT INTO user_course_mappings (
                project_id,
                end_user_id,
                course_id,
                assigned_by,
                assigned_date
            ) VALUES (
                p_project_id,
                v_user_id,
                v_course_id,
                p_assigned_by,
                NOW()
            )
            ON CONFLICT (end_user_id, course_id) DO NOTHING;

            IF FOUND THEN
                v_count := v_count + 1;
            END IF;
        END LOOP;
    END LOOP;

    RETURN v_count;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

