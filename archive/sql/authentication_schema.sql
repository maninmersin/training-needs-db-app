-- =====================================================
-- TRIGGERS
-- =====================================================

-- Updated timestamp trigger function (reuse from main schema if exists)
CREATE OR REPLACE FUNCTION update_auth_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Apply updated_at trigger to relevant tables
CREATE TRIGGER update_auth_users_updated_at
    BEFORE UPDATE ON auth_users
    FOR EACH ROW EXECUTE FUNCTION update_auth_updated_at_column();

CREATE TRIGGER update_auth_roles_updated_at
    BEFORE UPDATE ON auth_roles
    FOR EACH ROW EXECUTE FUNCTION update_auth_updated_at_column();

CREATE TRIGGER update_auth_two_factor_auth_updated_at
    BEFORE UPDATE ON auth_two_factor_auth
    FOR EACH ROW EXECUTE FUNCTION update_auth_updated_at_column();

