// A link that opens Outlook on the web with a NEW MEETING already filled in (title, time, place, notes, people).
// The person looking at it presses Send, so the meeting goes out from their own mailbox as a normal meeting
// request (Accept / Decline, shows in everyone's calendar). Pure: text in, text out.

export const DEFAULT_OUTLOOK_BASE = 'https://outlook.office.com';

// Browsers cope with much longer, but Outlook on the web may cut a very long link
export const LONG_LINK = 6000;

const enc = encodeURIComponent;

/** The notes shown in the meeting: who runs it, where, and who is invited. */
function notesFor(state) {
  const lines = [];
  if (state.trainer) lines.push(`Trainer: ${state.trainer}`);
  if (state.functionalArea) lines.push(`Department: ${state.functionalArea}`);
  if (state.room) lines.push(`Room: ${state.room}`);
  lines.push('', 'Generated by Training Needs Database System');
  return lines.join('\n');
}

/**
 * @param {Object} item - a NEW item from planInviteChanges ({ current: meeting state })
 * @param {Object} [options]
 * @param {boolean} [options.testMode] - only `testEmail` is invited and the title says [TEST]
 * @param {string} [options.testEmail]
 * @param {string} [options.base] - 'https://outlook.office.com' (work or school); 'https://outlook.live.com' for a personal account
 * @returns {{ url: string, length: number, tooLong: boolean, people: number }}
 */
export function outlookComposeLink(item, { testMode = false, testEmail = '', base = DEFAULT_OUTLOOK_BASE } = {}) {
  const state = item.current;
  const people = testMode ? [String(testEmail).trim()] : state.attendees.map((person) => person.email);
  const title = `${testMode ? '[TEST] ' : ''}${state.title}`;
  const notes = testMode ? `TEST - this meeting is only being sent to you.\n\n${notesFor(state)}` : notesFor(state);

  const query = [
    'path=%2Fcalendar%2Faction%2Fcompose',
    'rru=addevent',
    `subject=${enc(title)}`,
    `startdt=${enc(`${state.start}:00`)}`,
    `enddt=${enc(`${state.end}:00`)}`,
    `location=${enc([state.location, state.room ? `Room ${state.room}` : ''].filter(Boolean).join(' - '))}`,
    `body=${enc(notes)}`,
    `to=${enc(people.join(';'))}`
  ].join('&');

  const url = `${base.replace(/\/+$/, '')}/calendar/0/deeplink/compose?${query}`;
  return { url, length: url.length, tooLong: url.length > LONG_LINK, people: people.length };
}
