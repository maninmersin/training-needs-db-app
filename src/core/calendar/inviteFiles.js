// Turning planned invite changes into .ics files. Pure: text in, text out (no database, no download).
//
// Two files at most, because an .ics file has ONE method for the whole file:
//   - invitations and updates (METHOD:REQUEST): the meeting's permanent UID, its version number (SEQUENCE) and
//     everyone invited, so Outlook updates the existing meeting instead of adding a second one
//   - cancellations (METHOD:CANCEL): the whole meeting, or just the people who were removed
import { createEvents } from 'ics';
import { KIND } from './planChanges';

const pad = (n) => String(n).padStart(2, '0');

const parseWall = (text) => {
  const [date, time] = text.split('T');
  const [year, month, day] = date.split('-').map(Number);
  const [hour, minute] = time.split(':').map(Number);
  return [year, month, day, hour, minute];
};

/** True for a name Intl knows, such as Europe/London. */
export function isValidTimeZone(timeZone) {
  try {
    new Intl.DateTimeFormat('en-US', { timeZone });
    return true;
  } catch {
    return false;
  }
}

const offsetMs = (timestamp, timeZone) => {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone, hourCycle: 'h23', year: 'numeric', month: 'numeric', day: 'numeric', hour: 'numeric', minute: 'numeric', second: 'numeric'
  }).formatToParts(new Date(timestamp));
  const value = Object.fromEntries(parts.filter((part) => part.type !== 'literal').map((part) => [part.type, Number(part.value)]));
  return Date.UTC(value.year, value.month - 1, value.day, value.hour, value.minute, value.second) - timestamp;
};

/** [y, m, d, h, mi] on a wall clock in `timeZone` -> the same instant as UTC [y, m, d, h, mi], allowing for daylight saving. */
export function wallClockToUtc([year, month, day, hour, minute], timeZone) {
  const guess = Date.UTC(year, month - 1, day, hour, minute);
  const first = offsetMs(guess, timeZone);
  let utc = guess - first;
  const second = offsetMs(utc, timeZone);
  if (second !== first) utc = guess - second;
  const date = new Date(utc);
  return [date.getUTCFullYear(), date.getUTCMonth() + 1, date.getUTCDate(), date.getUTCHours(), date.getUTCMinutes()];
}

/** Times as the `ics` library wants them: real UTC when the location has a time zone, else "floating" local times. */
const timesFor = (state, timeZone) => {
  const start = parseWall(state.start);
  const end = parseWall(state.end);
  if (timeZone) {
    return {
      start: wallClockToUtc(start, timeZone), end: wallClockToUtc(end, timeZone),
      startInputType: 'utc', startOutputType: 'utc', endInputType: 'utc', endOutputType: 'utc'
    };
  }
  return { start, end, startInputType: 'local', startOutputType: 'local', endInputType: 'local', endOutputType: 'local' };
};

const describe = (state, extra) => {
  const lines = [];
  if (extra) lines.push(extra, '');
  if (state.trainer) lines.push(`Trainer: ${state.trainer}`);
  if (state.functionalArea) lines.push(`Department: ${state.functionalArea}`);
  if (state.room) lines.push(`Room: ${state.room}`);
  if (state.attendees.length > 0) {
    lines.push('', 'Attendees:');
    state.attendees.forEach((person) => lines.push(`- ${person.name}`));
  }
  lines.push('', 'Generated by Training Needs Database System');
  return lines.join('\n');
};

/** Why the organiser cannot be used, or null if it is fine. */
export function validateOrganizer(organizer) {
  if (!organizer || !String(organizer.email || '').trim()) return 'Set an organiser email address before creating invites.';
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(organizer.email.trim())) return 'The organiser email address is not a full address.';
  return null;
}

const sanitize = (text) => String(text || 'Training').replace(/[^a-zA-Z0-9\-_]/g, '_').replace(/_+/g, '_').replace(/^_+|_+$/g, '').slice(0, 50) || 'Training';

const toAttendee = (person) => ({ name: person.name, email: person.email, rsvp: true, partstat: 'NEEDS-ACTION', role: 'REQ-PARTICIPANT' });

function collectEvents(items, { organizer, timeZones = {}, testMode = false, testEmail = '' } = {}) {
  const organizerProblem = validateOrganizer(organizer);
  if (organizerProblem) return { error: organizerProblem, requests: [], cancellations: [], warnings: [] };
  if (testMode && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(testEmail).trim())) {
    return { error: 'Test mode needs a test email address, so nothing is sent to the real attendees.', requests: [], cancellations: [], warnings: [] };
  }

  const warnings = [];
  const zoneFor = (location) => {
    const zone = timeZones[location];
    if (!zone) return null;
    if (isValidTimeZone(zone)) return zone;
    const message = `"${zone}" is not a valid time zone for ${location}; its times were left as local times.`;
    if (!warnings.includes(message)) warnings.push(message);
    return null;
  };
  const testPerson = { name: 'Test recipient', email: String(testEmail).trim() };
  const prefix = testMode ? '[TEST] ' : '';
  const base = { organizer: { name: organizer.name || 'Training Coordinator', email: organizer.email.trim() }, productId: 'training-needs-db' };

  const requests = [];
  const cancellations = [];

  items.forEach((item) => {
    const uid = testMode ? `test-${item.uid}` : item.uid;
    const withTest = (people) => (testMode ? [testPerson] : people).map(toAttendee);
    const notice = testMode ? 'TEST - this was not sent to the real attendees.' : null;

    if (item.kind === KIND.NEW || item.kind === KIND.UPDATE) {
      const state = item.current;
      const extra = [notice, item.kind === KIND.UPDATE ? `Updated: ${item.changes.length ? `${item.changes.join(', ')} changed` : 'attendees changed'}` : null].filter(Boolean).join('\n');
      requests.push({
        ...base, ...timesFor(state, zoneFor(state.location)), uid, sequence: item.sequence, method: 'REQUEST', status: 'CONFIRMED',
        title: `${prefix}${state.title}`, description: describe(state, extra), location: state.location,
        attendees: withTest(state.attendees), busyStatus: 'BUSY', categories: ['Training']
      });
    }

    // People who were invited before and are not now are cancelled from the meeting they had
    const cancelWho = item.removed;
    if ((item.kind === KIND.CANCEL || item.kind === KIND.CANCEL_ATTENDEES || item.kind === KIND.UPDATE) && cancelWho.length > 0 && item.previous) {
      const state = item.previous;
      cancellations.push({
        ...base, ...timesFor(state, zoneFor(state.location)), uid, sequence: item.sequence, method: 'CANCEL', status: 'CANCELLED',
        title: `${prefix}${state.title}`, description: describe({ ...state, attendees: [] }, [notice, 'This meeting has been cancelled.'].filter(Boolean).join('\n')),
        location: state.location, attendees: withTest(cancelWho), categories: ['Training']
      });
    }
  });

  return { requests, cancellations, warnings, prefix };
}

/**
 * @param {Array} items - from planInviteChanges
 * @param {Object} options
 * @param {{ name: string, email: string }} options.organizer
 * @param {Object} [options.timeZones] - { [location name]: IANA time zone }; locations not listed use floating times
 * @param {boolean} [options.testMode] - titles say TEST, UIDs are different, and ONLY `testEmail` is invited
 * @param {string} [options.testEmail]
 * @param {string} [options.label] - used in the file names, for example the schedule name
 * @param {Date} [options.now]
 * @returns {{ error?: string, files: Array<{ kind, filename, content, count }>, warnings: string[] }}
 */
export function buildInviteFiles(items, options = {}) {
  const { label = 'Training', now = new Date(), testMode = false } = options;
  const { error, requests, cancellations, warnings } = collectEvents(items, options);
  if (error) return { error, files: [], warnings };

  const stamp = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
  const name = (kind) => `${testMode ? 'TEST_' : ''}${sanitize(label)}_${kind}_${stamp}.ics`;
  const files = [];
  for (const [kind, events] of [['Invites', requests], ['Cancellations', cancellations]]) {
    if (events.length === 0) continue;
    const { error, value } = createEvents(events);
    if (error) return { error: `Calendar file could not be created: ${error.message || error}`, files: [], warnings };
    files.push({ kind: kind === 'Invites' ? 'invites' : 'cancellations', filename: name(kind), content: value, count: events.length });
  }
  return { files, warnings };
}

// ---------------------------------------------------------------------------
// Email drafts (.eml). Opening one in Outlook gives a new, unsent message already addressed to the attendees,
// with the meeting inside it as a calendar part (the same way Outlook's own invitations travel). The sender
// only has to press Send, and each attendee gets Accept / Decline in the email.
// ---------------------------------------------------------------------------
const ascii = (text) => /^[ -~]*$/.test(text);
const base64 = (text) => btoa(unescape(encodeURIComponent(text)));
const wrap64 = (text) => (base64(text).match(/.{1,76}/g) || []).join('\r\n');
const header = (text) => (ascii(text) ? text : `=?UTF-8?B?${base64(text)}?=`);
const address = ({ name, email }) => (name ? `"${String(name).replace(/["\\\r\n]/g, '')}" <${email}>` : email);
const shown = (parts, utc) => `${pad(parts[2])}/${pad(parts[1])}/${parts[0]} ${pad(parts[3])}:${pad(parts[4])}${utc ? ' (UTC)' : ''}`;

const emailFor = (event, { organizer, now }) => {
  const when = `${shown(event.start, event.startInputType === 'utc')} to ${shown(event.end, event.endInputType === 'utc')}`;
  const cancelled = event.method === 'CANCEL';
  const body = [
    cancelled ? `This meeting has been cancelled: ${event.title}` : `You are invited to: ${event.title}`,
    `When: ${when}`,
    event.location ? `Where: ${event.location}` : null,
    '',
    event.description
  ].filter((line) => line !== null).join('\r\n');
  const { error, value } = createEvents([event]);
  if (error) return { error: `Calendar file could not be created: ${error.message || error}` };

  const boundary = `----=_training_${now.getTime().toString(36)}`;
  const lines = [
    `From: ${address(organizer)}`,
    `To: ${event.attendees.map(address).join(', ')}`,
    `Subject: ${header(cancelled ? `Cancelled: ${event.title}` : event.title)}`,
    `Date: ${now.toUTCString().replace('GMT', '+0000')}`,
    'X-Unsent: 1',
    'MIME-Version: 1.0',
    `Content-Type: multipart/alternative; boundary="${boundary}"`,
    '',
    `--${boundary}`,
    'Content-Type: text/plain; charset=utf-8',
    'Content-Transfer-Encoding: base64',
    '',
    wrap64(body),
    `--${boundary}`,
    `Content-Type: text/calendar; charset=utf-8; method=${event.method}`,
    'Content-Transfer-Encoding: base64',
    '',
    wrap64(value),
    `--${boundary}--`,
    ''
  ];
  return { content: lines.join('\r\n') };
};

/**
 * One .eml draft per meeting (and per cancellation). Same inputs as buildInviteFiles.
 * @returns {{ error?: string, files: Array<{ kind: 'email', filename, content, count }>, warnings: string[] }}
 */
export function buildInviteEmails(items, options = {}) {
  const { label = 'Training', now = new Date(), testMode = false, organizer } = options;
  const { error, requests, cancellations, warnings } = collectEvents(items, options);
  if (error) return { error, files: [], warnings };

  const files = [];
  for (const event of [...requests, ...cancellations]) {
    const email = emailFor(event, { organizer: { name: organizer.name || 'Training Coordinator', email: organizer.email.trim() }, now });
    if (email.error) return { error: email.error, files: [], warnings };
    const kind = event.method === 'CANCEL' ? 'Cancel' : 'Invite';
    files.push({ kind: 'email', filename: `${testMode ? 'TEST_' : ''}${sanitize(label)}_${kind}_${sanitize(event.title)}_${files.length + 1}.eml`, content: email.content, count: 1 });
  }
  return { files, warnings };
}
